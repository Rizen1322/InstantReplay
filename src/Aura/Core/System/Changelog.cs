    /// <summary>
    /// Что показать человеку, который обновился с <paramref name="from"/> на
    /// <paramref name="to"/>. Пропущенные версии не теряются: обновившийся через
    /// две-три сборки увидит всё, что вышло за это время.
    /// </summary>
    public static IReadOnlyList<ChangelogEntry> Between(Version? from, Version to)
    {
        if (from is null) return [];

        var result = new List<ChangelogEntry>();
        foreach (var entry in Entries)
        {
            if (!Version.TryParse(entry.Version, out var version)) continue;
            if (version > from && version <= to) result.Add(entry);
        }
        return result;
    }

    /// <summary>Версия из настроек. Пусто или мусор — считаем, что предыдущей не было.</summary>
    public static Version? Parse(string? value) =>
        Version.TryParse(value, out var version) ? version : null;
