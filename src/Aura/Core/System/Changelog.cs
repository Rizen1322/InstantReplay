// Пространство имён — SystemIntegration, а не System: внутри Aura.Core короткое
// «System» перекрыло бы системное, и System.Threading перестал бы находиться.
namespace Aura.Core.SystemIntegration;

/// <summary>Что нового в одной версии: заголовок и короткие строчки по делу.</summary>
public sealed record ChangelogEntry(string Version, string Headline, string[] Items);

/// <summary>
/// Список изменений, который человек видит после обновления.
///
/// Живёт в коде, а не тянется из релиза на GitHub: показать его нужно сразу после
/// запуска новой версии, в том числе без интернета, и текст должен точно
/// соответствовать той сборке, которая только что установилась.
///
/// Пишется для пользователя, а не для разработчика: что изменилось в его работе,
/// а не какие классы переехали. Версии — новые сверху.
/// </summary>
public static class Changelog
{
    public static readonly ChangelogEntry[] Entries =
    [
        new("1.1.42", "Скриншоты стали полноценными",
        [
            "PrintScreen — снимок выбранного куска экрана: выделяете рамкой то, что нужно, и сразу дорисовываете стрелки, прямоугольники и линии от руки. Семь цветов, красный по умолчанию.",
            "Выделение не приходится угадывать с первого раза: рамку можно тянуть за любой край, двигать целиком или обвести другое место — снимок под ней остаётся тем же.",
            "Alt+PrintScreen снимает весь экран одной клавишей, без лишних окон.",
            "Готовый кадр уходит в буфер обмена по Ctrl+C и вставляется куда угодно, а Ctrl+S кладёт его в папку.",
            "У скриншотов теперь своя папка — она выбирается на вкладке «Файлы» отдельно от видео. Файлы называются по порядку: Screenshot_1, Screenshot_2 и дальше.",
            "В «Клипах» снимки стоят рядом с записями, а правая кнопка предлагает «Копировать» — картинка сразу в буфере.",
            "Подпись над сеткой перестала называть всё подряд записями и говорит состав: сколько видео и сколько скриншотов.",
        ]),

        new("1.1.41", "Жёлтой рамки вокруг экрана больше нет",
        [
            "Windows рисовала рамку поверх экрана всё время, пока идёт запись, и в клипы она попадала тоже. Теперь Aura получает у системы официальное разрешение снимать без неё.",
            "Если разрешение не выдано, приложение один раз откроет нужную страницу параметров Windows и покажет, что включить, — вместо того чтобы молча писать с рамкой.",
        ]),
    ];

    /// <summary>
    /// Что показать человеку, который обновился с <paramref name="from"/> на
    /// <paramref name="to"/>. Пропущенные версии не теряются: обновившийся через
    /// две-три сборки увидит всё, что вышло за это время.
    /// </summary>
    public static IReadOnlyList<ChangelogEntry> Between(Version? from, Version to)
    {
        if (from is null) return [];

        var result = new List<ChangelogEntry>();
        foreach (var entry in Entries)
        {
            if (!Version.TryParse(entry.Version, out var version)) continue;
            if (version > from && version <= to) result.Add(entry);
        }
        return result;
    }

    /// <summary>Версия из настроек. Пусто или мусор — считаем, что предыдущей не было.</summary>
    public static Version? Parse(string? value) =>
        Version.TryParse(value, out var version) ? version : null;
}
